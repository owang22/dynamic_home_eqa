"""Replay a finished run's actions through the current world rules, with no model.

Every action the residents took (events.jsonl, in the order the run applied them)
is applied again to a fresh World built from household.json. With the placement
rules off and the assumed areas this should rebuild the run's own snapshots (the
`match` check); with them on it shows what the same choices would have produced
under the new rules. The residents' choices are fixed, so this measures the rules,
not how residents would react to them (a refused put_down in the replay is forced
to where it went in the run, and counted).

    python -m lived_home.replay_rules <run> [--rules] [--measured] [--fix-starts] [--out f.json]
"""
from __future__ import annotations

import argparse
import copy
import json
import pathlib

from lived_home import measured_areas
from lived_home.layout import Layout
from lived_home.world import World, clock

SNAPSHOT_TIMES = [h * 60 for h in range(8, 23, 2)]


def _act(e: dict, world: World) -> dict | None:
    v = e["verb"]
    if v == "go":
        return {"verb": "go", "place": e["to"]}
    if v in ("pick_up", "pocket", "wear"):
        return {"verb": v, "object": e["object"]}
    if v == "give":
        return {"verb": "give", "object": e["object"], "person": e.get("person")}
    if v == "do":
        to = e.get("to")
        return {"verb": "do", "place": to if to in world.layout.places else "", "minutes": 1}
    if v == "leave_home":
        return {"verb": "leave_home", "minutes": e.get("minutes") or 30}
    if v == "put_down":
        to = e.get("to_pos") or {}
        return {"verb": "put_down", "object": e["object"],
                "place": to.get("place") if to.get("at") == "place" else "",
                "relation": e.get("relation_as_said") or e.get("relation") or "",
                "ref": e.get("ref_as_said") or e.get("ref") or ""}
    return None                                    # say, interrupted: nothing moves


def replay(run: pathlib.Path, rules: bool = False, measured: bool = False,
           fix_starts: bool = False) -> dict:
    spec = json.loads((run / "household.json").read_text())
    objs = copy.deepcopy(spec["objects"])
    layout = Layout.from_json(spec["layout"])
    moved = []
    if measured:
        measured_areas.apply(layout, spec.get("scene"))
    if fix_starts:
        from lived_home.household import fix_start_placement
        moved = fix_start_placement(objs, layout)
    rids = [r["id"] for r in spec["residents"]]
    world = World(layout, {o["id"]: o for o in objs}, rids,
                  {r["id"]: r["sleeps_at"] for r in spec["residents"]},
                  names={r["id"]: r["name"].split()[0] for r in spec["residents"]})
    world.rules = {"holding": rules, "places": rules}
    events = [json.loads(l) for l in (run / "events.jsonl").read_text().splitlines() if l.strip()]
    days = sorted({e["day"] for e in events})
    snaps, stats = [], {"applied": 0, "failed": [], "forced": 0, "redirected": 0, "over_room": [],
                        "moved_at_start": moved}
    i = 0
    for d in days:
        world.day = d
        for person in world.people.values():
            if person.at is None and person.back_at >= 24 * 60:
                person.back_at -= 24 * 60
        todo = list(SNAPSHOT_TIMES)
        while i < len(events) and events[i]["day"] == d:
            e = events[i]
            while todo and e["minute"] >= todo[0]:
                world.minute_now = todo[0]
                snaps.append((d, clock(todo.pop(0)).replace(":", ""), world.positions(spec.get("scene"))))
            i += 1
            rid, minute = e["resident"], e["minute"]
            if e["verb"] == "come_home":
                p = world.people[rid]
                p.back_at = min(p.back_at, minute)
                world.come_home_if_due(rid, minute)
                continue
            if e.get("implied") and e["verb"] != "go":
                continue                        # regenerated by the action it belongs to
            act = _act(e, world)
            if act is None:
                continue
            n_log = len(world.log)
            ok, msg, _ = world.apply(rid, act, minute)
            if ok:
                stats["applied"] += 1
                stats["redirected"] += sum(1 for x in world.log[n_log:] if x.get("redirected"))
                continue
            if "no room" in msg and e["verb"] == "put_down":
                # the residents cannot be asked again: carry out the rules' choice, over the room
                real_full, world._full = world._full, lambda *a, **k: ""
                n_log = len(world.log)
                ok, msg2, _ = world.apply(rid, act, minute)
                world._full = real_full
                if ok:
                    stats["over_room"].append({"day": d, "time": e["time"], "object": e["object"],
                                               "message": msg})
                    stats["redirected"] += sum(1 for x in world.log[n_log:] if x.get("redirected"))
                    continue
            stats["failed"].append({"day": d, "time": e["time"], "resident": rid, "act": act, "message": msg})
            to = e.get("to_pos")
            if e["verb"] == "put_down" and to and world.holder_of(e["object"]) == rid:
                world._release(world.people[rid], e["object"])     # put where the run put it
                world.where[e["object"]] = dict(to)
                stats["forced"] += 1
        for t in todo:
            world.minute_now = t
            snaps.append((d, clock(t).replace(":", ""), world.positions(spec.get("scene"))))
        world.minute_now = None
        world.end_of_day()
    return {"spec": spec, "snaps": snaps, "stats": stats}


def match(run: pathlib.Path, snaps: list) -> dict:
    """How many object positions in the replayed snapshots equal the run's own."""
    same = total = 0
    worst = []
    for d, t, st in snaps:
        f = run / f"day_{d:02d}" / f"positions_{t}.json"
        if not f.exists():
            continue
        orig = json.loads(f.read_text())["objects"]
        key = lambda o: (o.get("place"), o["relation"], o.get("reference"))
        diff = [oid for oid in orig if key(orig[oid]) != key(st["objects"][oid])]
        same += len(orig) - len(diff)
        total += len(orig)
        if diff:
            worst.append((d, t, len(diff)))
    return {"same": same, "total": total, "share": round(same / max(1, total), 4),
            "snapshots_with_a_difference": len(worst), "first": worst[:5]}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("run", type=pathlib.Path)
    ap.add_argument("--rules", action="store_true", help="placement rules on")
    ap.add_argument("--measured", action="store_true", help="measured spot areas")
    ap.add_argument("--fix-starts", action="store_true", help="start positions moved by the rules")
    ap.add_argument("--out", type=pathlib.Path)
    a = ap.parse_args()
    from lived_home.check_placement import check, report
    r = replay(a.run, a.rules, a.measured, a.fix_starts)
    st = r["stats"]
    print(f"applied {st['applied']}, failed {len(st['failed'])} (forced back {st['forced']}), "
          f"redirected {st['redirected']}, put down over the room limit {len(st['over_room'])}, "
          f"moved at start {len(st['moved_at_start'])}")
    print("match with the run's own snapshots:", match(a.run, r["snaps"]))
    res = check(a.run, snaps=r["snaps"], spec=r["spec"])
    print(report(res))
    if a.out:
        a.out.write_text(json.dumps({"stats": {k: v for k, v in st.items()}, "check": res}, indent=1))


if __name__ == "__main__":
    main()
