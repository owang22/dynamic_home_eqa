#!/usr/bin/env python3
"""Render the prompts the log-and-notes arm would see on hh_s2 (8-a-day rare-mover bank) without a
server: the client's own replay_only mode returns no completion and never connects, so every
room choice falls back to the rotation and every night records model_call_failed. The prompt
TEXT is what we want (the fields it carries), not the model's answers. Writes
PROMPTS_seen_by_the_arm.md with the day-1 and day-14 nightly prompts and one search-time choice
and answer prompt from each of those days.

    PYTHONPATH=src python3 coordination/studies/study4_rare_things_that_matter/dump_prompts_seen_by_the_arm.py
"""
import inspect, json, pathlib, shutil, sys, tempfile
sys.path.insert(0, "src")
from baselines.patrol.llm import LLMClient
from self_improve import overnight_wave as ow
from self_improve import search_driven as sd
from self_improve.frozen_household import FrozenHousehold

HERE = pathlib.Path(__file__).resolve().parent
BANK = pathlib.Path("results/self_improve/varied_homes/rare_movers/banks_8_a_day/hh_s2_t03.jsonl")
ARM = "the log and notes about the routine"
LAST_DAY = 14
CAPTURED = []


class Capturing(LLMClient):
    def complete(self, messages, schema, max_tokens):
        caller = next((f.function for f in inspect.stack()[1:6]
                       if f.function in ("write_the_notes_about_the_routine", "run_one_search")), "?")
        CAPTURED.append({"caller": caller, "messages": messages, "schema": schema, "max_tokens": max_tokens})
        return None, {}


def main():
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="prompts_dry_run_"))
    cache = tmp / "cache"
    client = Capturing(cache, replay_only=True)
    household = FrozenHousehold(BANK)
    how, sensing, _ = ow.ARMS[ARM]
    was = sd.LOCKED
    sd.LOCKED = ow.NO_LENGTH_LIMIT
    try:
        sd.run_one_cell(household, how, sensing, client, tmp / "cell", last_day=LAST_DAY,
                        questions_per_day=99, budget=3, seed=0, tell_it_what_it_ruled_out=True,
                        name_the_objects_it_will_be_quizzed_on=ow.NAME_THE_QUIZ_LIST)
    finally:
        sd.LOCKED = was
    nightly = [c for c in CAPTURED if c["caller"] == "write_the_notes_about_the_routine"]
    searches = [c for c in CAPTURED if c["caller"] == "run_one_search"]
    def day_of(c):
        txt = "\n".join(m["content"] for m in c["messages"])
        import re
        m = re.search(r"[Dd]ay (\d+)", txt)
        return int(m.group(1)) if m else None
    def block(title, c):
        out = [f"### {title}", "", f"max_tokens {c['max_tokens']}; schema keys: {list((c['schema'] or {}).get('properties', {}).keys()) if c['schema'] else None}", ""]
        for m in c["messages"]:
            out += [f"**{m['role']}**", "", "```", m["content"], "```", ""]
        return "\n".join(out)
    parts = ["# Prompts the log-and-notes arm sees (hh_s2, 8-a-day rare-mover bank), rendered without a server",
             "", f"Dry run on {BANK}: the client's replay_only mode returns no completion, so rooms fall back to the rotation and",
             "every night is a failed call; the prompt text is what the arm would be shown. Generated by dump_prompts_seen_by_the_arm.py.",
             f"{len(nightly)} nightly prompts and {len(searches)} search-time prompts were captured over days 0-{LAST_DAY}.", ""]
    for want in (1, 14):
        n = [c for c in nightly if day_of(c) == want]
        parts.append(block(f"Nightly note-writing prompt, day {want}", n[-1] if n else nightly[min(want, len(nightly) - 1)]))
    # one choice + one answer prompt from day 1 and day 14 (the first search of those days)
    for want in (1, 14):
        s_ = [c for c in searches if day_of(c) == want]
        choice = next((c for c in s_ if c["schema"] and "room" in c["schema"].get("properties", {})), None)
        answer = next((c for c in s_ if c["schema"] and "room" not in c["schema"].get("properties", {})), None)
        if choice: parts.append(block(f"Search-time room-choice prompt, day {want}", choice))
        if answer: parts.append(block(f"Search-time answer prompt, day {want}", answer))
    (HERE / "PROMPTS_seen_by_the_arm.md").write_text("\n".join(parts))
    print(f"wrote {HERE / 'PROMPTS_seen_by_the_arm.md'}; nightly {len(nightly)}, searches {len(searches)}")
    shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
